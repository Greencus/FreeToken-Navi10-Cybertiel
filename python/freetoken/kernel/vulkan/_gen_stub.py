"""Regenerate the .pyi stub for the raw pybind module from its live API.

The fork's handwritten ``freetoken_vulkan_ext.pyi`` went stale (it predated
the fused-MoE, GPU-router and async-upload bindings). This script introspects
the *loaded* extension and emits matching stubs:

  * ``freetoken_vulkan_ext.pyi``  - full generated stub (do not hand-edit)
  * ``ext.pyi`` / ``ext_module.pyi`` - re-export shims for the stable names

Usage:  python -m freetoken.kernel.vulkan._gen_stub
"""
from __future__ import annotations

import pathlib
import re

_PKG_DIR = pathlib.Path(__file__).resolve().parent

# pybind renders C++ types with these spellings; rewrite to clean Python.
_TYPE_MAP = [
    ("collections.abc.Sequence[typing.SupportsInt]", "list[int]"),
    ("collections.abc.Sequence[typing.SupportsFloat]", "list[float]"),
    ("collections.abc.Sequence[str]", "list[str]"),
    ("collections.abc.Sequence[", "list["),
    ("typing.SupportsInt", "int"),
    ("typing.SupportsFloat", "float"),
    ("typing.SupportsIndex", "int"),
]

# Known no-arg stats helpers: specialize the generic tuple return.
_RET_OVERRIDES = {
    "desc_cache_stats": "tuple[int, int, int, int, int, int]",
    "batch_barrier_stats": "tuple[int, int]",
    "batch_submit_count": "tuple[int, int]",
    "batch_upload_async_stats": "tuple[int, int]",
}


def _rewrite_types(sig: str) -> str:
    for old, new in _TYPE_MAP:
        sig = sig.replace(old, new)
    return sig


def _split_params(params: str) -> list[str]:
    """Split a pybind signature parameter list on top-level commas."""
    out, depth, cur = [], 0, []
    for ch in params:
        if ch in "[(":
            depth += 1
        elif ch in "])":
            depth -= 1
        if ch == "," and depth == 0:
            out.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    if "".join(cur).strip():
        out.append("".join(cur).strip())
    return out


def _emit_stub(mod) -> str:
    lines = [
        "# GENERATED by freetoken.kernel.vulkan._gen_stub from the live",
        "# freetoken_vulkan_ext pybind module. Regenerate with:",
        "#     python -m freetoken.kernel.vulkan._gen_stub",
        "# Do not hand-edit.",
        "",
        "from __future__ import annotations",
        "",
        "import torch",
        "",
    ]
    names = sorted(n for n in dir(mod) if not n.startswith("_"))
    for name in names:
        obj = getattr(mod, name)
        doc = (getattr(obj, "__doc__", None) or "").strip("\n")
        if not callable(obj) or not doc:
            lines.append(f"{name}: object  # (non-callable or undocumented)")
            continue
        first, _, rest = doc.partition("\n")
        first = first.strip()
        m = re.match(r"^(\w+)\((.*)\) -> (.+)$", first, re.S)
        if not m:
            lines.append(f"# UNPARSED: {first!r}")
            continue
        fname, params_s, ret = m.group(1), m.group(2), m.group(3).strip()
        ret = _RET_OVERRIDES.get(name, _rewrite_types(ret))
        params = [_rewrite_types(p) for p in _split_params(params_s)]
        # pybind permits a default in the MIDDLE of the arg list (e.g.
        # batch_moe_record's gu_slot0/dn_slot0 followed by the output
        # tensors); that is invalid Python stub syntax. Such calls are
        # positional-only in practice, so emit every parameter as required.
        default_idx = next(
            (i for i, p in enumerate(params) if "=" in p), None
        )
        if default_idx is not None and any(
            "=" not in p for p in params[default_idx:]
        ):
            params = [p.split("=", 1)[0].strip() for p in params]
        sig = f"def {name}({', '.join(params)}) -> {ret}:"
        desc = rest.strip()
        if desc:
            # Keep the fork's own descriptions, one docstring line per line.
            doc_lines = desc.split("\n")
            body = "\n".join('    """' + doc_lines[0] if i == 0 else "    " + ln
                             for i, ln in enumerate(doc_lines))
            body += '\n    """\n    ...\n'
            lines.append(sig)
            lines.append(body)
        else:
            lines.append(sig)
            lines.append("    ...")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    from freetoken.kernel.vulkan import require_ext

    mod = require_ext()
    stub = _emit_stub(mod)
    target = _PKG_DIR / "freetoken_vulkan_ext.pyi"
    target.write_text(stub)
    alias_body = (
        '"""Alias stub: the raw pybind module (see freetoken_vulkan_ext.pyi)."""\n'
        "from .freetoken_vulkan_ext import *  # noqa: F401,F403\n"
    )
    for alias in ("ext.pyi", "ext_module.pyi"):
        (_PKG_DIR / alias).write_text(alias_body)
    n_funcs = sum(
        1
        for line in stub.splitlines()
        if line.startswith("def ")
    )
    print(f"wrote {target} ({n_funcs} functions), ext.pyi, ext_module.pyi")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
